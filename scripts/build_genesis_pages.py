#!/usr/bin/env python3
"""Generate the chapter stubs of the Genesis four-lens reader.

Writes content/library/genesis-woh/lenses/1.md … 50.md (template genesis-chapter.html). The
stubs carry only frontmatter: the page body is rendered by the template from
data/library/genesis-woh/chapter-N.json (lens 1 Hebrew + transliteration,
lens 2 the Wheel of Heaven literal translation) and, when it exists,
data/library/genesis-woh/lenses/chapter-N.json (lens 3 Reading, lens 4
Meaning). The section page content/library/genesis-woh/lenses/_index.md is hand-written and is
never touched here.

The description depends on whether the chapter's lens file is published
(status "stable"): a draft lens file renders only on the dev server
(config.extra.genesis_show_drafts), so its stub still describes the chapter as
Hebrew + literal.

English only (v1). Run from the www repo root:

    python3 scripts/build_genesis_pages.py          # or: mise run genesis
    python3 scripts/build_genesis_pages.py --check  # exit 1 if a stub is stale
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BOOK = ROOT / "data" / "library" / "genesis-woh"
LENSES = BOOK / "lenses"
OUT = ROOT / "content" / "library" / "genesis-woh" / "lenses"

# Reading groups on the section page; the chapter stub records its group so
# the chapter page can name it without recomputing the ranges.
GROUPS = (
    ("primeval", "Primeval history", 1, 11),
    ("abraham", "Abraham", 12, 25),
    ("jacob", "Jacob", 26, 36),
    ("joseph", "Joseph", 37, 50),
)


def group_of(n: int) -> tuple[str, str]:
    for key, name, lo, hi in GROUPS:
        if lo <= n <= hi:
            return key, name
    raise SystemExit(f"chapter {n} is outside every group")


def toml_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def chapter_title(meta_title: str, n: int) -> str:
    """'Genesis 1 — When the Elohim began to shape' -> 'When the Elohim began to shape'."""
    prefix = f"Genesis {n} — "
    return meta_title[len(prefix):] if meta_title.startswith(prefix) else meta_title


def lens_status(n: int) -> str:
    f = LENSES / f"chapter-{n}.json"
    if not f.exists():
        return ""
    return json.loads(f.read_text(encoding="utf-8")).get("lens", {}).get("status", "")


def description(n: int, title: str, four: bool) -> str:
    if four:
        text = (f"Genesis {n}, “{title}”, in four lenses: the Hebrew, a literal translation, "
                "a reading with the decoded words, and its meaning in plain language.")
        short = (f"Genesis {n} in four lenses: the Hebrew, a literal translation, "
                 "a decoded reading, and the meaning of each verse in plain language.")
    else:
        text = (f"Genesis {n}, “{title}”: the Hebrew with transliteration beside the "
                "Wheel of Heaven literal translation, verse by verse.")
        short = (f"Genesis {n} in Hebrew with transliteration beside the Wheel of Heaven "
                 "literal translation, verse by verse. Reading and Meaning lenses are coming.")
    return text if len(text) <= 160 else short


def render(n: int, meta_title: str, verses: int) -> str:
    title = chapter_title(meta_title, n)
    group_key, group_name = group_of(n)
    four = lens_status(n) == "stable"
    lines = [
        "+++",
        f"title = {toml_str(f'Genesis {n}')}",
        f"description = {toml_str(description(n, title, four))}",
        'template = "genesis-chapter.html"',
        f"weight = {n}",
        "",
        "[extra]",
        "# GENERATED by scripts/build_genesis_pages.py — edit the script, not this file.",
        f"chapter = {n}",
        f"chapter_title = {toml_str(title)}",
        f"verses = {verses}",
        f"group = {toml_str(group_key)}",
        f"group_name = {toml_str(group_name)}",
        'schema_type = "Chapter"',
        "+++",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="report stale stubs, write nothing")
    args = ap.parse_args()

    meta = json.loads((BOOK / "_meta.json").read_text(encoding="utf-8"))
    files = sorted(meta["chapterFiles"], key=lambda c: c["n"])
    if [c["n"] for c in files] != list(range(1, 51)):
        raise SystemExit("genesis-woh/_meta.json: expected chapters 1-50")

    OUT.mkdir(parents=True, exist_ok=True)
    stale = []
    for c in files:
        path = OUT / f"{c['n']}.md"
        text = render(c["n"], c["title"], c["paragraphs"])
        if path.exists() and path.read_text(encoding="utf-8") == text:
            continue
        stale.append(path.relative_to(ROOT).as_posix())
        if not args.check:
            path.write_text(text, encoding="utf-8")

    if args.check:
        if stale:
            print("stale:", *stale, sep="\n  ")
            return 1
        print("content/library/genesis-woh/lenses stubs are current")
        return 0
    print(f"content/library/genesis-woh/lenses: {len(stale)} stub(s) written, {len(files) - len(stale)} unchanged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
